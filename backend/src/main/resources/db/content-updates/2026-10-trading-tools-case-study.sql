## 系统架构

```text
通达信主源 / 东财备用源 / Tushare 历史数据
                ↓
       后台轮询与交易日历
                ↓
  K 线聚合 / 量价形态 / 日内动量 / 异动检测
        ↓                 ↓
SQLite 行情与信号       期权链与每日快照
        ↓                 ↓
     PySide6 桌面壳 + Vue 3 / ECharts 页面
                ↓
      原生通知 / 浮窗 / 系统托盘
```

GUI 与行情采集线程分离：后台线程负责网络请求、计算和持久化，主线程只通过 Qt Signal 接收不可变结果并更新界面，避免轮询阻塞交互。前端页面使用 Vue 3 + TypeScript 构建后嵌入 QWebEngineView，Python 通过受控桥接调用完成数据渲染。

## 关键工程判断

### 1. 双数据源不是简单的失败重试

行情接口会出现节点不可达、单 IP 间歇拒绝、字段临时为空和盘中数据滞后。主源启动时探测可用节点并记录延迟，运行中断线重连；备用源只在主源不可用时限速兜底，避免高频请求反而触发更严格限制。

交易日、交易时段和午休窗口集中在统一日历模块判断，所有轮询任务复用同一套规则，避免每个数据源各自理解“现在是否应该有新行情”。

### 2. 信号必须经过回测，也必须公开失败结论

量价形态并非只凭经验设定。我为规则提供了多标的回测、参数扫描和特征诊断工具，并把手续费与基准收益纳入验证。

结果显示：部分量价买入形态在当前个股样本上没有表现出正期望；日内动量方向具有统计显著性，但标的单次平均幅度可能小于 ETF 期权买卖价差。因此当前版本把它们定位为方向参考和人工复核提醒，而不是机械交易依据。

项目保留这些负面结果，因为“知道规则在哪些场景无效”比只展示几次成功信号更重要。

### 3. 期权链需要同时解决实时与历史口径

实时 T 型报价、分钟 K、历史日 K 和合约元数据来自不同接口，代码、到期日和价格单位并不天然一致。系统在边界层统一合约编码、时间与数值口径，过滤零成交产生的全零 K 线，并在同一到期月份内选择策略腿，避免跨月组合让最大盈亏计算失真。

期权快照按交易日持久化，使波动率、持仓量和期限结构可以跨日比较，而不是只展示当前瞬间。

### 4. AI 能力要服从产品可信度

项目曾实现基于 DeepSeek 的结构化期权策略建议，能够组合行情、技术面、期权链和历史走势生成候选策略。经过产品边界评估后，当前界面主动移除了这一入口，底层实验代码仍保留。

原因是模型输出容易被误解为确定性交易建议，而盯盘工具的目标是呈现数据、触发提醒和辅助人工判断。对于无法稳定验证的能力，选择从用户界面撤下，而不是为了“有 AI”继续展示。

### 5. 桌面打包必须考虑 Web 与 Qt 两套运行时

应用同时依赖 Qt、WebEngine、ECharts 和本地 Python 模块。PyInstaller 配置显式包含 WebEngine 组件、前端构建产物及第三方数据文件；页面加载完成前到达的数据先按渲染函数去重入队，待 WebView ready 后补发最后一份，避免启动首轮行情被静默丢弃。

